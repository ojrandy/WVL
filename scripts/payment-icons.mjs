// Payment method brand icons (update.md §4, D.2).
//
//   node scripts/payment-icons.mjs --download   fetch the SVGs from Simple Icons into src/assets/payment-icons/
//   node scripts/payment-icons.mjs              rebuild src/assets/payment-icons/index.ts from those SVGs
//
// Simple Icons is CC0 1.0; the marks stay trademarks of their owners and are only used, unmodified except
// for colour, to identify the method next to its name. The generated module holds the path data, so the
// app needs no SVG imports, no raw HTML and no requests to other sites. scripts/paymentIcons.test.ts
// fails if index.ts drifts from the SVGs.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const SIMPLE_ICONS_VERSION = '16.34.0';
export const ICON_DIR = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'assets', 'payment-icons');

// Slug → colour used (update.md §4 table). Wise and Western Union use a darker colour than the
// Simple Icons one, which is too light on white.
export const ICON_COLOURS = {
  paypal: '#002991',
  bitcoin: '#F7931A',
  tether: '#50AF95',
  ethereum: '#3C3C3D',
  zelle: '#6D1ED4',
  cashapp: '#00C244',
  venmo: '#008CFF',
  applepay: '#000000',
  googlepay: '#4285F4',
  wise: '#163300',
  revolut: '#191C1F',
  westernunion: '#1A1A1A',
  moneygram: '#DA291C',
};

/** Title and the single path of a Simple Icons SVG (24×24 viewBox). */
export function parseSimpleIcon(svg, slug) {
  if (!/viewBox="0 0 24 24"/.test(svg)) throw new Error(`${slug}: expected a 0 0 24 24 viewBox`);
  const title = svg.match(/<title>([^<]+)<\/title>/)?.[1];
  const paths = [...svg.matchAll(/<path d="([^"]+)"\s*\/>/g)].map((m) => m[1]);
  if (!title || paths.length !== 1) throw new Error(`${slug}: expected one <title> and one <path>`);
  if (/<script|on\w+=|href=/i.test(svg)) throw new Error(`${slug}: unexpected content in the SVG`);
  return { title, path: paths[0] };
}

/** The contents of index.ts for the SVGs in `dir`. */
export function renderIconModule(dir = ICON_DIR) {
  const entries = Object.entries(ICON_COLOURS).map(([slug, color]) => {
    const { title, path } = parseSimpleIcon(readFileSync(join(dir, `${slug}.svg`), 'utf8'), slug);
    return `  ${slug}: {\n    title: ${JSON.stringify(title)},\n    color: '${color}',\n    path: ${JSON.stringify(path)},\n  },`;
  });
  return [
    `// Generated by scripts/payment-icons.mjs from the Simple Icons ${SIMPLE_ICONS_VERSION} SVGs in this folder (CC0 1.0).`,
    '// Do not edit by hand: run `node scripts/payment-icons.mjs`. The marks are trademarks of their owners.',
    '',
    'export interface BrandIcon {',
    '  title: string;',
    '  color: string;',
    '  /** Path data for a 0 0 24 24 viewBox. */',
    '  path: string;',
    '}',
    '',
    'export const PAYMENT_BRAND_ICONS: Record<string, BrandIcon> = {',
    ...entries,
    '};',
    '',
  ].join('\n');
}

async function download() {
  for (const slug of Object.keys(ICON_COLOURS)) {
    const url = `https://cdn.jsdelivr.net/npm/simple-icons@${SIMPLE_ICONS_VERSION}/icons/${slug}.svg`;
    const res = await fetch(url);
    if (!res.ok) throw new Error(`${slug}: HTTP ${res.status} from ${url}`);
    const svg = await res.text();
    parseSimpleIcon(svg, slug);
    writeFileSync(join(ICON_DIR, `${slug}.svg`), svg);
    console.log(`downloaded ${slug}.svg`);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (process.argv.includes('--download')) await download();
  writeFileSync(join(ICON_DIR, 'index.ts'), renderIconModule());
  console.log(`wrote ${join(ICON_DIR, 'index.ts')}`);
}
